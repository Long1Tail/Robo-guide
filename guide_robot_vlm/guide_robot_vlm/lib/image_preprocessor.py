"""Модуль: image_preprocessor.py

ОПИСАНИЕ БУДУЩЕГО ФУНКЦИОНАЛА
=============================

Назначение:
-----------
Модуль чистой логики (БЕЗ импорта rclpy) для подготовки кадров камеры к подаче в VLM.

Ключевые функции:
-----------------
1. `ImagePreprocessor`:
   - Прием сырого изображения в виде буфера байтов RGB/BGR (полученного из sensor_msgs/Image через CvBridge).
   - Масштабирование кадра (downscale / letterbox resize) под входное разрешение модели
     (например, 640x480 или 448x448 для Qwen2.5-VL / SmolVLM).
     Цель: снижение потребления видеопамяти и ускорение передачи по сети.
   - Сжатие кадра в формат JPEG с настраиваемым качеством (jpeg_quality: 75-85%).
   - Преобразование байт JPEG в Base64 Data URL (`data:image/jpeg;base64,...`) для включения
     в стандартный payload OpenAI-совместимого API.
   - Фильтрация устаревших кадров по таймстампу (отбрасывание кадров старше max_frame_age_s).

2. Структуры данных:
   - `PreprocessedImage`: неизменяемый датакласс, содержащий base64-строку, итоговые размеры
     (ширина, высота), временную метку захвата кадра и размер сжатого буфера.

Особенности и инварианты:
-------------------------
- Не зависит от ROS 2;
- Покрывается быстрыми юнит-тестами на Pillow / OpenCV без поднятия нод и оборудования.
"""
