"""Модуль: vlm_backends.py

ОПИСАНИЕ БУДУЩЕГО ФУНКЦИОНАЛА
=============================

Назначение:
-----------
Модуль чистой логики (БЕЗ импорта rclpy), реализующий абстракцию и конкретные клиенты
для мультимодальных моделей (Vision-Language Models).

Архитектурные сущности:
-----------------------
1. Протокол `VlmBackend` (Protocol):
   - `predict(messages, image_b64, json_schema, abort_event) -> VlmResponse`:
     отправка запроса с текстом и изображением, ожидание ответа с проверкой прерывания.
   - `health() -> tuple[bool, str]`:
     проверка доступности эндпоинта инференса (healthcheck перед активацией ноды).

2. Реализации:
   - `VllmBackend`:
     HTTP-клиент к серверу vLLM или OpenAI-совместимому API.
     Поддерживает передачу картинки по схеме data:image/jpeg;base64 и принудительное
     ограничение структуры ответа по JSON Schema (guided decoding через Outlines/XGrammar).
   - `LlamaCppVlmBackend`:
     HTTP-клиент к локальному llama-server с поддержкой мультимодального проектора (mmproj)
     и GBNF-грамматиками.
   - `OpenAIVlmBackend`:
     Клиент к облачным сервисам (GPT-4o-mini, Qwen-VL-Max) с ключом из переменной окружения.
   - `MockVlmBackend`:
     Детерминированный стаб для юнит-тестов и CI без запуска видеокарт и сетевых запросов.

3. Структура `VlmResponse`:
   - Содержит распарсенный JSON, сырой текст, затраченное время инференса (latency_ms)
     и метаданные модели.
"""
